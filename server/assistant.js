async function askAssistant(messages, context) {
  if (!ai.getClient()) {
    return fallbackAnswer(messages[messages.length - 1]?.content || '');
  }

  const contextBlock = context ? `
Контекст (текущие данные):
- Всего лидов: ${context.totalLeads || '—'}
- Новых сегодня: ${context.todayLeads || '—'}
- Активных сделок: ${context.activeDeals || '—'}
- Последний лид: ${context.lastLead || '—'}
` : '';

  const systemPrompt = `Ты — ассистент менеджера по продажам натяжных потолков «Потолок Пати».${contextBlock}

Твои задачи:
1. Помогать менеджеру отвечать клиентам — давать готовые формулировки для мессенджеров
2. Подсказывать варианты решений под задачу клиента
3. Отвечать на FAQ по продукции
4. Помогать составлять КП и сообщения

Важно:
- Отвечай кратко, конкретно
- Если нужен текст для клиента — оберни его в кавычки
- Если вопрос не по теме — предложи уточнить
- Цены указывай только из прайса компании`;

  try {
    const fullMessages = [{ role: 'system', content: systemPrompt }, ...messages.slice(-10)];
    const content = await ai.tryCompletion(fullMessages, null, 800, 0.5);
    return { role: 'assistant', content };
  } catch (err) {
    return { role: 'assistant', content: fallbackAnswer(messages[messages.length - 1]?.content || '') };
  }
}

function fallbackAnswer(text) {
  const lower = text.toLowerCase();

  for (const faq of FAQ) {
    if (faq.q.some(k => lower.includes(k))) return faq.a;
  }

  return 'Чем могу помочь? Могу подсказать цены, сроки, помочь с текстом для клиента или составить КП. Напишите ваш вопрос.';
}

function generateMessageTemplate(type, data) {
  const templates = {
    measurement_confirmation: (d) =>
      `Здравствуйте, ${d.name}! Запись на замер confirmed на ${d.date || 'завтра'} в ${d.time || '10:00'}. ` +
      `Замерщик приедет по адресу: ${d.address || 'уточним'}. Ориентировочная длительность — 30 мин. ` +
      `С собой: рулетка, стремянка, образцы. До встречи!`,

    quote_followup: (d) =>
      `Здравствуйте, ${d.name}! Отправили вам смету на ${d.ceilingType || 'потолок'}. ` +
      `Сумма: ${d.total ? d.total.toLocaleString() + ' ₽' : 'по смете'}. ` +
      `Готовы ответить на вопросы и согласовать удобное время для замера.`,

    installation_reminder: (d) =>
      `Напоминаем: установка потолка завтра в ${d.time || '10:00'} по адресу: ${d.address || 'уточнённому'}. ` +
      `Монтаж займёт 2–4 часа. Пожалуйста, освободите комнату от мебели по возможности. ` +
      `По вопросам: +7 (XXX) XXX-XX-XX`,

    lead_first: (d) =>
      `Здравствуйте, ${d.name}! Спасибо за заявку на потолок. ` +
      `Подскажите, какой тип потолка вас интересует и какая площадь комнаты? ` +
      `Могу сразу сделать примерный расчёт.`,
  };

  const fn = templates[type];
  return fn ? fn(data) : null;
}

